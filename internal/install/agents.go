// Package install copies the climan skill into coding agents' global skills
// folders.
package install

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/jasonli0226/climan/internal/platform"
)

// Marker follows the frontmatter of every SKILL.md climan installs; files
// without it are never overwritten.
const Marker = "<!-- generated by climan; rerun climan install to update -->"

const agentNames = "claude, pi or opencode"

// Agent is one coding agent climan can install into.
type Agent struct {
	Name      string
	ConfigDir string // the agent counts as installed when this dir exists
	SkillsDir string
}

// Agents returns every supported agent, in output order. Paths follow
// docs/research/agent-skill-dirs.md.
func Agents(env platform.Env) []Agent {
	// Claude's docs say CLAUDE_CONFIG_DIR replaces ~/.claude for settings,
	// sessions and plugins but do not name skills; its binary suggests
	// skills move too, so honor it.
	claude := envOr(env, "CLAUDE_CONFIG_DIR", filepath.Join(env.Home, ".claude"))
	pi := envOr(env, "PI_CODING_AGENT_DIR", filepath.Join(env.Home, ".pi", "agent"))
	// opencode uses ~/.config on every OS, Windows and macOS included.
	opencode := filepath.Join(envOr(env, "XDG_CONFIG_HOME", filepath.Join(env.Home, ".config")), "opencode")
	return []Agent{agent("claude", claude), agent("pi", pi), agent("opencode", opencode)}
}

func agent(name, dir string) Agent {
	return Agent{Name: name, ConfigDir: dir, SkillsDir: filepath.Join(dir, "skills")}
}

func envOr(env platform.Env, name, fallback string) string {
	if v := env.Vars[name]; v != "" {
		return v
	}
	return fallback
}

// Detected returns the agents whose config dir exists.
func Detected(agents []Agent) []Agent {
	var out []Agent
	for _, a := range agents {
		if fi, err := os.Stat(a.ConfigDir); err == nil && fi.IsDir() {
			out = append(out, a)
		}
	}
	return out
}

// Select returns the named agents in table order. Blank names are dropped
// and repeats collapse; an unknown name, or no name at all, is an error.
func Select(agents []Agent, names []string) ([]Agent, error) {
	want := map[string]bool{}
	for _, n := range names {
		if n = strings.TrimSpace(n); n != "" {
			want[n] = true
		}
	}
	if len(want) == 0 {
		return nil, errors.New("no agent named (want " + agentNames + ")")
	}
	var out []Agent
	for _, a := range agents {
		if want[a.Name] {
			out = append(out, a)
			delete(want, a.Name)
		}
	}
	for n := range want {
		return nil, fmt.Errorf("unknown agent %q (want %s)", n, agentNames)
	}
	return out, nil
}
